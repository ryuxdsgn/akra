#!/usr/bin/env python3
"""Local dots.tts voiceover (RedNote, Apache-2.0 weights: commercial use allowed) for non-English
channels such as Indonesian. Runs on Apple Silicon through the MLX port (int4, ~2.4 GB).

Setup once (from the project root):
  uv venv -p 3.12 .venv-dots
  uv pip install -p .venv-dots/bin/python "git+https://github.com/sb1992/dots-tts-mlx.git@v0.2.0" "huggingface_hub[hf_xet]"
  .venv-dots/bin/hf download shraey/dots-tts-mlx --include "int4/*" --local-dir .models/dots-tts-mlx

  .venv-dots/bin/python dots_tts.py <episode.json> --out render/<channel>/ep-001/assets \
      --ref channels/<channel>/voice_ref.wav --ref-text-file channels/<channel>/voice_ref.txt \
      [--text-file tts.txt] [--language ID] [--seed 7] [--speed 1.0] [--take a]

--ref is a clean 5-15 s clip of the channel voice (your own voice or a licensed one; never clone a
person without consent). --ref-text-file is what the clip says (better clone than x-vector only).

Text: one phrase per line (= one breath); a blank line = a beat (+0.45 s). Pieces joined by " | " on one
line ("Merah. | Kuning. | Hijau.") are spoken in one go, then cut at the pauses between them and spaced
--piece-gap apart: use it for counting and other one-word lines, which the model cannot say alone. Each line is generated by a
separate dots-tts process, so memory is freed between lines: on an 8 GB Mac a line peaks near 6 GB and a
30 s clip in one go would not fit. Expect ~1.5 min per line on an M1.
Numbers are spoken as Indonesian words (language ID). Captions still show the script text.

Runaway guard: on very short lines (one word such as "Hijau.") the model sometimes does not stop and babbles
for seconds. A line longer than max_seconds() is generated again with another seed (up to --retries times);
the shortest try is kept and reported. Lines are cached in <out>/.dots-cache/ (keyed by text, voice, seed,
speed, model), so a re-run only generates lines that changed or were never accepted.

Word timings: `npx hyperframes transcribe` (whisper small, this language) on the joined take; per line,
if whisper heard the same number of words as the script line, its timings are used, otherwise the line's
time is shared out by word length. So transcript.json always has exactly the script's words.
Writes voiceover_<take>.mp3 + transcript_<take>.json, and copies them to voiceover.mp3 / transcript.json.
"""
import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile

BEAT = 0.45
RETRY_SEED = 1000
PIECE = "|"
_WORD = re.compile(r"[A-Za-z0-9]")

_ONES = ["nol", "satu", "dua", "tiga", "empat", "lima", "enam", "tujuh", "delapan", "sembilan",
         "sepuluh", "sebelas"]


def angka(n):
    """Indonesian words for 0 <= n < 1,000,000."""
    if n < 12:
        return _ONES[n]
    if n < 20:
        return f"{_ONES[n - 10]} belas"
    if n < 100:
        return f"{_ONES[n // 10]} puluh" + (f" {_ONES[n % 10]}" if n % 10 else "")
    if n < 1000:
        head = "seratus" if n // 100 == 1 else f"{_ONES[n // 100]} ratus"
        return head + (f" {angka(n % 100)}" if n % 100 else "")
    if n < 1_000_000:
        head = "seribu" if n // 1000 == 1 else f"{angka(n // 1000)} ribu"
        return head + (f" {angka(n % 1000)}" if n % 1000 else "")
    return str(n)


def speak_text(line, language):
    """Text sent to the model: pronunciation hints dropped, numbers spelled out for Indonesian."""
    line = re.sub(r"\s*\([^)]*\)", "", line)
    if language == "ID":
        line = re.sub(r"\b(\d{1,6})x\b", lambda m: f"{angka(int(m.group(1)))} kali", line)
        line = re.sub(r"\b\d{1,6}\b", lambda m: angka(int(m.group(0))), line)
        line = line.replace("%", " persen")
    return line


def max_seconds(line):
    """Longest believable take for a line: 0.6 s a word + 0.6 s (calm 125 wpm is ~0.5 s a word)."""
    return 0.6 + 0.6 * max(1, len(words_of(line)))


def pieces_of(line):
    return [x.strip() for x in line.split(PIECE) if x.strip()]


def split_at_pauses(seg, sr, n, frame=0.02, floor=0.06, min_pause=0.06):
    """Cut samples into n pieces at the n-1 longest quiet runs; None when there are not enough pauses."""
    import numpy as np
    if n <= 1:
        return [seg]
    hop = int(frame * sr)
    rms = np.array([np.sqrt(np.mean(seg[i:i + hop] ** 2)) for i in range(0, len(seg) - hop + 1, hop)])
    quiet = rms < floor * rms.max()
    runs, start = [], None
    for i, q in enumerate(list(quiet) + [False]):
        if q and start is None:
            start = i
        elif not q and start is not None:
            if (i - start) * frame >= min_pause and start > 0 and i < len(quiet):
                runs.append((i - start, start, i))
            start = None
    if len(runs) < n - 1:
        return None
    cuts = sorted((a + b) // 2 * hop for _, a, b in sorted(runs, reverse=True)[:n - 1])
    edges = [0] + cuts + [len(seg)]
    return [seg[edges[k]:edges[k + 1]] for k in range(n)]


def cache_key(*parts):
    h = hashlib.sha1()
    for part in parts:
        h.update(part if isinstance(part, bytes) else str(part).encode())
        h.update(b"\0")
    return h.hexdigest()[:16]


def script_lines(text):
    """[(line, extra_pause_after)] with blank lines turned into beats."""
    out = []
    for ln in text.split("\n"):
        if ln.strip():
            out.append([ln.strip(), 0.0])
        elif out:
            out[-1][1] = BEAT
    return out


def words_of(line):
    return [w for w in re.sub(r"\s*\([^)]*\)", "", line).split() if _WORD.search(w)]


def share_out(words, start, end):
    """Spread a line's words over [start, end] by character length."""
    total = sum(len(w) for w in words) or 1
    out, t = [], start
    for w in words:
        d = (end - start) * len(w) / total
        out.append([w, round(t, 3), round(t + d * 0.92, 3)])
        t += d
    return out


def time_words(lines, spans, heard):
    """Script words with timings: whisper's where the line's word count matches, else shared out."""
    out, fallback = [], 0
    for (line, _), (s, e) in zip(lines, spans):
        want = words_of(line)
        got = [w for w in heard if s - 0.08 <= w["start"] < e + 0.08]
        if len(got) == len(want):
            out += [[w, round(g["start"], 3), round(g["end"], 3)] for w, g in zip(want, got)]
        else:
            fallback += 1
            out += share_out(want, s, e)
    return out, fallback


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("episode")
    ap.add_argument("--out", required=True)
    ap.add_argument("--ref", required=True)
    ap.add_argument("--ref-text-file")
    ap.add_argument("--text-file")
    ap.add_argument("--language", default="ID", help="uppercase ISO code for dots.tts (ID, EN, ...)")
    ap.add_argument("--model", default=".models/dots-tts-mlx/int4")
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--speed", type=float, default=1.0)
    ap.add_argument("--take", default="a", help="name for this take (voiceover_<take>.mp3)")
    ap.add_argument("--retries", type=int, default=3, help="extra seeds tried when a line runs too long")
    ap.add_argument("--piece-gap", type=float, default=1.5, help="silence between ' | ' pieces of one line (s)")
    a = ap.parse_args()

    ep = json.load(open(a.episode, encoding="utf-8"))
    text = open(a.text_file, encoding="utf-8").read() if a.text_file else ep["script"]
    lines = script_lines(text)
    norm = lambda w: re.sub(r"[^a-z0-9]", "", w.lower())
    sw = [norm(w) for w in words_of(ep["script"])]
    tw = [norm(w) for ln, _ in lines for w in words_of(ln)]
    if sw != tw:
        k = next((i for i, (x, y) in enumerate(zip(sw, tw)) if x != y), min(len(sw), len(tw)))
        sys.exit(f"text differs from the episode script at word {k} ({len(tw)} vs {len(sw)} words)")
    ref_text = open(a.ref_text_file, encoding="utf-8").read().strip() if a.ref_text_file else None
    cli = os.path.join(os.path.dirname(sys.executable), "dots-tts")

    import numpy as np
    import soundfile as sf
    os.makedirs(a.out, exist_ok=True)
    cache = os.path.join(a.out, ".dots-cache")
    os.makedirs(cache, exist_ok=True)
    voice = open(a.ref, "rb").read() + (ref_text or "").encode()

    def trim(seg, rate):
        loud = np.flatnonzero(np.abs(seg) > 0.02 * np.abs(seg).max())
        return seg[max(0, loud[0] - int(0.04 * rate)):loud[-1] + int(0.06 * rate)] if len(loud) else seg

    def generate(i, line, seed, tmp):
        """One dots-tts run (cached): trimmed mono float32 samples and the sample rate."""
        text = speak_text(" ".join(pieces_of(line)), a.language)
        hit = os.path.join(cache, cache_key(text, voice, seed, a.speed, a.language, a.model) + ".wav")
        if not os.path.exists(hit):
            cmd = [cli, "--model", a.model, "--text", text, "--ref-audio", a.ref, "--language", a.language,
                   "--seed", str(seed), "--out-path", tmp, "--out-prefix", f"l{i:03d}s{seed}"]
            if ref_text:
                cmd += ["--ref-text", ref_text]
            if a.speed != 1.0:
                cmd += ["--speed", str(a.speed)]
            subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL)
            wav = sorted(f for f in os.listdir(tmp) if f.startswith(f"l{i:03d}s{seed}"))[-1]
            os.replace(os.path.join(tmp, wav), hit)
        seg, rate = sf.read(hit, dtype="float32")
        if seg.ndim > 1:
            seg = seg.mean(axis=1)
        return trim(seg, rate), rate

    parts, spans, units, t, sr, runaway = [], [], [], 0.0, None, []
    with tempfile.TemporaryDirectory() as tmp:
        for i, (line, beat) in enumerate(lines):
            print(f"[{i + 1}/{len(lines)}] {line}", flush=True)
            pcs = pieces_of(line)
            limit, tries = max_seconds(line), []
            for k in range(a.retries + 1):
                seg, sr = generate(i, line, a.seed + i + k * RETRY_SEED, tmp)
                cut = split_at_pauses(seg, sr, len(pcs))
                tries.append((cut is None, len(seg), seg, cut))
                if len(seg) / sr <= limit and cut is not None:
                    break
                why = "no pause between pieces" if cut is None else f"too long ({len(seg) / sr:.1f} s > {limit:.1f} s)"
                print(f"    {why}, new seed", flush=True)
            bad, _, seg, cut = min(tries, key=lambda x: x[:2])
            if bad or len(seg) / sr > limit:
                runaway.append(f"{line} ({len(seg) / sr:.1f} s)")
            if cut is not None and len(pcs) > 1:
                for piece_text, piece in zip(pcs[:-1], cut[:-1]):
                    piece = trim(piece, sr)
                    spans.append((t, t + len(piece) / sr))
                    units.append((piece_text, 0.0))
                    parts += [piece, np.zeros(int(a.piece_gap * sr), dtype=piece.dtype)]
                    t += len(piece) / sr + a.piece_gap
                seg, line = trim(cut[-1], sr), pcs[-1]
            elif len(pcs) > 1:
                line = " ".join(pcs)
            units.append((line, beat))
            n = len(line.split())
            gap = 0.16 + min(0.22, 0.018 * n) + (0.1 if line[-1:] in "?:" else 0.0) + beat
            spans.append((t, t + len(seg) / sr))
            parts += [seg, np.zeros(int(gap * sr), dtype=seg.dtype)]
            t += len(seg) / sr + gap
        audio = np.concatenate(parts[:-1])
        wav_path = os.path.join(tmp, "take.wav")
        sf.write(wav_path, audio, sr)
        mp3 = os.path.join(a.out, f"voiceover_{a.take}.mp3")
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", wav_path, "-ar", "44100", "-b:a", "128k", mp3], check=True)
        lang = a.language.lower()
        subprocess.run(["npx", "--no-install", "hyperframes", "transcribe", wav_path, "-e", "whisper", "-m", "small",
                        "-l", lang, "-d", tmp], check=True, stdout=subprocess.DEVNULL)
        heard = [w for w in json.load(open(os.path.join(tmp, "transcript.json"))) if _WORD.search(w["text"])]
    words, fallback = time_words(units, spans, heard)
    for r in runaway:
        print(f"! still too long after {a.retries} retries, listen: {r}")
    out = [{"text": w, "start": s, "end": e, "id": f"w{i}"} for i, (w, s, e) in enumerate(words)]
    tr = os.path.join(a.out, f"transcript_{a.take}.json")
    json.dump(out, open(tr, "w"), indent=2, ensure_ascii=False)
    for src, dst in ((mp3, "voiceover.mp3"), (tr, "transcript.json")):
        open(os.path.join(a.out, dst), "wb").write(open(src, "rb").read())
    print(f"take {a.take}: {mp3}  {len(audio) / sr:.2f}s  {len(out)} words"
          + (f"  ({fallback} line(s) with estimated word timings: check captions)" if fallback else ""))


if __name__ == "__main__":
    main()
